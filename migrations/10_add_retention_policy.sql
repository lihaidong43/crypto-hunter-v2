-- 添加数据保留策略
-- 自动删除超过 180 天（半年）的数据，节省存储空间

-- ============================================
-- 1. 添加数据保留策略
-- ============================================

-- 删除 180 天前的数据（每天自动执行）
SELECT add_retention_policy('market_snapshots', INTERVAL '180 days', if_not_exists => true);

-- ============================================
-- 2. 查看当前策略配置
-- ============================================

SELECT * FROM timescaledb_information.jobs 
WHERE hypertable_name = 'market_snapshots';

-- ============================================
-- 完成
-- ============================================

SELECT 'market_snapshots 数据保留策略已添加：保留最近 180 天（半年）数据' AS message;
